import AppKit
import Foundation

struct ClipboardEntry: Identifiable, Codable, Hashable {
    enum Content: Codable, Hashable {
        case text(String)
        /// File name of a PNG inside `ClipboardStore.directory`.
        case image(String)
        case files([String])
    }

    let id: UUID
    let content: Content
    let date: Date
    let appName: String?
    let appBundleID: String?

    var isImage: Bool {
        if case .image = content { return true }
        return false
    }

    var searchText: String {
        switch content {
        case .text(let text): text
        case .image: "image"
        case .files(let paths): paths.joined(separator: "\n")
        }
    }
}

/// Records the general pasteboard. There is no change notification, so it polls the change count.
final class ClipboardStore: ObservableObject {
    static let maxEntries = 200
    private static let recordingKey = "clipboard.recording"
    private static let maxTextLength = 200_000

    // Set by password managers and similar; never record these.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    static let directory: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let directory = base.appendingPathComponent("MenuBoard/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        return directory
    }()

    private static let storeFile = directory.appendingPathComponent("history.json")

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var lastCopiedID: UUID?
    @Published var isRecording: Bool {
        didSet { UserDefaults.standard.set(isRecording, forKey: Self.recordingKey) }
    }

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var timer: Timer?
    private var imageCache: [String: NSImage] = [:]
    private var iconCache: [String: NSImage] = [:]

    init() {
        isRecording = UserDefaults.standard.object(forKey: Self.recordingKey) as? Bool ?? true
        lastChangeCount = pasteboard.changeCount
        if let data = try? Data(contentsOf: Self.storeFile),
           let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) {
            entries = saved
        }
        let timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer.tolerance = 0.2
        self.timer = timer
    }

    // MARK: Recording

    private func poll() {
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount
        guard isRecording, changeCount != ownChangeCount else { return }
        capture()
    }

    private func capture() {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skippedTypes) else { return }

        let content: ClipboardEntry.Content
        let fileOptions: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: fileOptions) as? [URL], !urls.isEmpty {
            content = .files(urls.map(\.path))
        } else if let string = pasteboard.string(forType: .string),
                  !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            content = .text(String(string.prefix(Self.maxTextLength)))
        } else if let image = NSImage(pasteboard: pasteboard), let name = Self.storeImage(image) {
            content = .image(name)
        } else {
            return
        }

        let app = NSWorkspace.shared.frontmostApplication
        let entry = ClipboardEntry(id: UUID(), content: content, date: Date(), appName: app?.localizedName, appBundleID: app?.bundleIdentifier)

        if let existing = entries.firstIndex(where: { $0.content == content }) {
            entries.remove(at: existing)
        }
        entries.insert(entry, at: 0)
        while entries.count > Self.maxEntries {
            deleteImage(for: entries.removeLast())
        }
        persist()
    }

    // MARK: Actions

    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        switch entry.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .files(let paths):
            pasteboard.writeObjects(paths.map { URL(fileURLWithPath: $0) as NSURL })
        case .image:
            if let image = image(for: entry) { pasteboard.writeObjects([image]) }
        }
        ownChangeCount = pasteboard.changeCount
        lastCopiedID = entry.id
        if let index = entries.firstIndex(where: { $0.id == entry.id }), index != 0 {
            entries.move(fromOffsets: IndexSet(integer: index), toOffset: 0)
            persist()
        }
    }

    func remove(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }
        deleteImage(for: entry)
        persist()
    }

    func clear() {
        let removed = entries
        entries.removeAll()
        removed.forEach(deleteImage)
        persist()
    }

    // MARK: Presentation helpers

    func image(for entry: ClipboardEntry) -> NSImage? {
        guard case .image(let name) = entry.content else { return nil }
        if let cached = imageCache[name] { return cached }
        guard let image = NSImage(contentsOf: Self.directory.appendingPathComponent(name)) else { return nil }
        imageCache[name] = image
        return image
    }

    func appIcon(for entry: ClipboardEntry) -> NSImage? {
        guard let bundleID = entry.appBundleID else { return nil }
        if let cached = iconCache[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        iconCache[bundleID] = icon
        return icon
    }

    // MARK: Storage

    private static func storeImage(_ image: NSImage) -> String? {
        guard let tiff = image.tiffRepresentation,
              let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) else { return nil }
        let name = UUID().uuidString + ".png"
        guard (try? png.write(to: directory.appendingPathComponent(name))) != nil else { return nil }
        return name
    }

    private func deleteImage(for entry: ClipboardEntry) {
        guard case .image(let name) = entry.content else { return }
        imageCache[name] = nil
        try? FileManager.default.removeItem(at: Self.directory.appendingPathComponent(name))
    }

    private func persist() {
        guard let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: Self.storeFile, options: .atomic)
    }
}
